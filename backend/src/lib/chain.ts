/// Addresses are stored lowercase everywhere (DB CHECK constraints enforce it).
/// viem returns checksummed addresses and raw logs return lowercase; mixing the
/// two produces two rows for one holder and a cap table that double-counts.
export function lc(address: string): string {
  return address.toLowerCase();
}
